data class MaterialSymbolAxes(
    val fill: Float = 0f,
    val weight: Int = 400,
    val grade: Int = 0,
    val opticalSize: Float = 24f
)

private val materialSymbolsFamilyCache = mutableMapOf<MaterialSymbolAxes, FontFamily>()

private fun TextUnit.materialSymbolOpticalSize(): Float {
    return value.coerceIn(20f, 48f)
}

@OptIn(ExperimentalTextApi::class)
private fun materialSymbolsFamily(axes: MaterialSymbolAxes): FontFamily {
    return materialSymbolsFamilyCache.getOrPut(axes) {
        FontFamily(
            Font(
                R.font.material_symbols_outlined,
                variationSettings = FontVariation.Settings(
                    FontVariation.Setting("FILL", axes.fill),
                    FontVariation.weight(axes.weight),
                    FontVariation.Setting("GRAD", axes.grade.toFloat()),
                    FontVariation.Setting("opsz", axes.opticalSize)
                )
            )
        )
    }
}

fun materialSymbolAxes(
    renderMode: MaterialSymbolRenderMode,
    fontSize: TextUnit,
    filled: Boolean = false
): MaterialSymbolAxes {
    val opticalSize = fontSize.materialSymbolOpticalSize()
    return when (renderMode) {
        MaterialSymbolRenderMode.Business -> MaterialSymbolAxes(
            fill = if (filled) 1f else 0f,
            weight = 400,
            grade = 0,
            opticalSize = opticalSize
        )
        MaterialSymbolRenderMode.Picker -> MaterialSymbolAxes(
            fill = if (filled) 1f else 0f,
            weight = if (filled) 500 else 400,
            grade = if (filled) 100 else 0,
            opticalSize = opticalSize
        )
    }
}

@Composable
private fun rememberMaterialSymbolVectorResId(name: String): Int {
    val context = LocalContext.current
    return remember(name, context.packageName) {
        listOf(
            "ms_${name}",
            "ic_ms_${name}",
            "material_symbol_${name}"
        ).firstNotNullOfOrNull { resourceName ->
            context.resources.getIdentifier(resourceName, "drawable", context.packageName)
                .takeIf { it != 0 }
        } ?: 0
    }
}

@Composable
fun BusinessMaterialSymbolIcon(
    name: String,
    modifier: Modifier = Modifier,
    fontSize: TextUnit = 20.sp,
    tint: Color = MaterialTheme.colorScheme.onSurface,
    filled: Boolean = false
) {
    val drawableResId = rememberMaterialSymbolVectorResId(name)
    if (drawableResId != 0) {
        Icon(
            painter = painterResource(id = drawableResId),
            contentDescription = null,
            modifier = modifier,
            tint = tint
        )
    } else {
        MaterialSymbolGlyph(
            name = name,
            modifier = modifier,
            fontSize = fontSize,
            tint = tint,
            axes = materialSymbolAxes(
                renderMode = MaterialSymbolRenderMode.Business,
                fontSize = fontSize,
                filled = filled
            )
        )
    }
}

