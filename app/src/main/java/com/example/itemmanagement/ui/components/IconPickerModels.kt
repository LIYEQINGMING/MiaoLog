fun materialSymbolGlyph(name: String): String? {
    val codePoint = MATERIAL_SYMBOL_LOOKUP[name]?.codePoint ?: return null
    return String(Character.toChars(codePoint))
}

@Composable
fun MaterialSymbolGlyph(
    name: String,
    modifier: Modifier = Modifier,
    fontSize: TextUnit = 20.sp,
    tint: Color = MaterialTheme.colorScheme.onSurface,
    axes: MaterialSymbolAxes = materialSymbolAxes(
        renderMode = MaterialSymbolRenderMode.Picker,
        fontSize = fontSize
    )
) {
    val glyph = materialSymbolGlyph(name)
    if (glyph != null) {
        Text(
            text = glyph,
            modifier = modifier,
            fontFamily = materialSymbolsFamily(axes),
            fontSize = fontSize,
            color = tint
        )
    } else {
        Text(
            text = "?",
            modifier = modifier,
            fontSize = fontSize,
            color = tint
        )
    }
}

/**
 * 图标来源统一模型
 */
sealed class IconSource {
    /**
     * 表情符号类型
     * @param code Unicode 字符
     */
    data class Emoji(val code: String) : IconSource()

    /**
     * 矢量图标类型 (Google Material Symbols)
     * @param name 图标名称
     */
    data class Vector(val name: String) : IconSource()

    /**
     * 自定义图片类型
     * @param uri 图片的本地或网络路径
     */
    data class Custom(val uri: String) : IconSource()

    /**
     * 无图标
     */
    object None : IconSource()

    /**
     * 转换为存储用的字符串
     */
    fun toPersistString(): String {
        return when (this) {
            is Emoji -> "EMOJI:$code"
            is Vector -> "VECTOR:$name"
            is Custom -> "CUSTOM:$uri"
            is None -> ""
        }
    }

    companion object {
        /**
         * 从存储的字符串解析回 IconSource
         */
        fun fromPersistString(value: String?): IconSource {
            if (value.isNullOrBlank()) return None
            return when {
                value.startsWith("EMOJI:") -> Emoji(value.removePrefix("EMOJI:"))
                value.startsWith("VECTOR:") -> Vector(value.removePrefix("VECTOR:"))
                value.startsWith("CUSTOM:") -> Custom(value.removePrefix("CUSTOM:"))
                // 兼容旧版本直接存储 Emoji 的情况
                else -> Emoji(value)
            }
        }
    }
}

